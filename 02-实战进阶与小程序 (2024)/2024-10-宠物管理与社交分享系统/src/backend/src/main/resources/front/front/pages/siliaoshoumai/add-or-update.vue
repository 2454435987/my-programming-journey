<script>
	import wPicker from "@/components/w-picker/w-picker.vue";

	export default {
		data() {
			return {
				ruleForm: {
												siliaobianhao: this.getUUID(),
																siliaomingcheng: '',
																tupian: '',
																siliaoguige: '',
																shihechongwu: '',
																zhuyishixiang: '',
																siliaoxiangqing: '',
																thumbsupnum: '',
																crazilynum: '',
																												price: '',
												},
																																												shihechongwuOptions: [],
				shihechongwuIndex: 0,
																																																												// 登陆用户信息
				user: {},
                                ro:{
                                   siliaobianhao : false,
                                   siliaomingcheng : false,
                                   tupian : false,
                                   siliaoguige : false,
                                   shihechongwu : false,
                                   zhuyishixiang : false,
                                   siliaoxiangqing : false,
                                   thumbsupnum : false,
                                   crazilynum : false,
                                   clicktime : false,
                                   price : false,
                                },
			}
		},
		components: {
			wPicker
		},
		computed: {
						
						
						
						
						
						
						
						
						
						
						
						
						
						
						
						
						
						
						
						
						
						
						
						
						
						
						
						
						
						
						
						
						
					},
		async onLoad(options) {
			let table = uni.getStorageSync("nowTable");
			// 获取用户信息
			let res = await this.$api.session(table);
			this.user = res.data;
			
						// ss读取
																																																																								
																																				// 自定义下拉框值
			this.shihechongwuOptions = "猫,狗,鼠,鸟,龟,通用".split(',')
																																													
			// 如果有登陆，获取登陆后保存的userid
			this.ruleForm.userid = uni.getStorageSync("userid")
			if (options.refid) {
				// 如果上一级页面传递了refid，获取改refid数据信息
				this.ruleForm.refid = options.refid;
				this.ruleForm.nickname = uni.getStorageSync("nickname");
			}
			// 如果是更新操作
			if (options.id) {
				this.ruleForm.id = options.id;
				// 获取信息
				res = await this.$api.info(`siliaoshoumai`, this.ruleForm.id);
				this.ruleForm = res.data;
			}
			// 跨表
			if(options.cross){
				var obj = uni.getStorageSync('crossObj');
				for (var o in obj){
					if(o=='siliaobianhao'){
					this.ruleForm.siliaobianhao = obj[o];
					this.ro.siliaobianhao = true;
					continue;
					}
					if(o=='siliaomingcheng'){
					this.ruleForm.siliaomingcheng = obj[o];
					this.ro.siliaomingcheng = true;
					continue;
					}
					if(o=='tupian'){
					this.ruleForm.tupian = obj[o];
					this.ro.tupian = true;
					continue;
					}
					if(o=='siliaoguige'){
					this.ruleForm.siliaoguige = obj[o];
					this.ro.siliaoguige = true;
					continue;
					}
					if(o=='shihechongwu'){
					this.ruleForm.shihechongwu = obj[o];
					this.ro.shihechongwu = true;
					continue;
					}
					if(o=='zhuyishixiang'){
					this.ruleForm.zhuyishixiang = obj[o];
					this.ro.zhuyishixiang = true;
					continue;
					}
					if(o=='siliaoxiangqing'){
					this.ruleForm.siliaoxiangqing = obj[o];
					this.ro.siliaoxiangqing = true;
					continue;
					}
					if(o=='thumbsupnum'){
					this.ruleForm.thumbsupnum = obj[o];
					this.ro.thumbsupnum = true;
					continue;
					}
					if(o=='crazilynum'){
					this.ruleForm.crazilynum = obj[o];
					this.ro.crazilynum = true;
					continue;
					}
					if(o=='clicktime'){
					this.ruleForm.clicktime = obj[o];
					this.ro.clicktime = true;
					continue;
					}
					if(o=='price'){
					this.ruleForm.price = obj[o];
					this.ro.price = true;
					continue;
					}
