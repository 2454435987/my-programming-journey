																																																																																																																																																																																																																																																																if(this.ruleForm.id){
					await this.$api.update(`yiqichongwuxinxi`, this.ruleForm);
				}else{
					await this.$api.add(`yiqichongwuxinxi`, this.ruleForm);
				}
